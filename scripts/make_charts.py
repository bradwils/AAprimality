#!/usr/bin/env python3
"""Turn results/*.csv into charts (results/*.png) and report-ready tables
(results/summary.md). Run from the repo root. Needs matplotlib."""
import csv
import math
import os
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

RES = "results"
ALGOS = ["fermat", "miller-rabin", "aks"]
LABEL = {"fermat": "Fermat", "miller-rabin": "Miller-Rabin", "aks": "AKS"}
COLOR = {"fermat": "#E69F00", "miller-rabin": "#0072B2", "aks": "#009E73"}
plt.rcParams.update({"figure.dpi": 150, "axes.grid": True, "grid.alpha": 0.3, "font.size": 11})
md = ["# Results summary", "", "Generated by `scripts/make_charts.py` from `results/*.csv`."]


def read(name, folder=RES):
    path = os.path.join(folder, name)
    if not os.path.exists(path):
        print("missing", path)
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def save(fig, name):
    fig.tight_layout()
    fig.savefig(os.path.join(RES, name))
    plt.close(fig)
    print("wrote", name)


def table(title, header, rows, note=""):
    md.extend(["", f"## {title}", ""])
    if note:
        md.extend([note, ""])
    md.append("| " + " | ".join(header) + " |")
    md.append("|" + "---|" * len(header))
    md.extend("| " + " | ".join(map(str, r)) + " |" for r in rows)


def fmt_ns(ns):
    for unit, scale in (("s", 1e9), ("ms", 1e6), ("µs", 1e3)):
        if ns >= scale:
            return f"{ns / scale:.3g} {unit}"
    return f"{ns:.3g} ns"


def slope(pts):
    xs, ys = [math.log(x) for x, _ in pts], [math.log(y) for _, y in pts]
    mx, my = sum(xs) / len(xs), sum(ys) / len(ys)
    return sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)


def time_vs_bits():
    rows = read("time_bits.csv")
    if not rows:
        return
    data = defaultdict(dict)
    for r in rows:
        data[r["algorithm"], r["family"]][int(r["bits"])] = float(r["median_ns"])
    fams = ["prime", "semiprime", "rand_composite"]
    TITLE = {"prime": "Primes", "semiprime": "Semiprimes", "rand_composite": "Random odd composites"}
    fig, axes = plt.subplots(1, 3, figsize=(14, 4.2), sharey=True)
    for ax, fam in zip(axes, fams):
        for a in ALGOS:
            d = data.get((a, fam), {})
            ax.plot(sorted(d), [d[b] for b in sorted(d)], "o-", ms=4, color=COLOR[a], label=LABEL[a])
        ax.set(yscale="log", xlabel="bits of n", title=TITLE[fam])
    axes[0].set_ylabel("time per call (ns, log scale)")
    axes[0].legend()
    save(fig, "time_vs_bits.png")

    cols = [8, 16, 24, 32, 48, 64]
    table("Median time per call", ["algorithm", "family"] + [f"{b} bits" for b in cols],
          [[LABEL[a], f] + [fmt_ns(data[a, f][b]) if b in data[a, f] else "—" for b in cols]
           for a in ALGOS for f in fams + ["prime_square"] if (a, f) in data],
          "Fermat and Miller-Rabin run with k = 9 rounds. — means not measured, because one call already took over 2 s at a smaller size.")

    fits = []
    for a in ALGOS:
        d = data.get((a, "prime"), {})
        pts = [(b, t) for b, t in d.items() if b >= 12]
        if len(pts) >= 3:
            fits.append([LABEL[a], f"{slope(pts):.2f}", f"{min(b for b, _ in pts)}–{max(b for b, _ in pts)}"])
    mr, ak = data.get(("miller-rabin", "prime"), {}), data.get(("aks", "prime"), {})
    common = max(set(mr) & set(ak), default=None)
    note = f"At {common}-bit primes AKS is {ak[common] / mr[common]:,.0f}× slower than Miller-Rabin (k = 9)." if common else ""
    table("How time grows with bit length on primes", ["algorithm", "log-log slope", "bit lengths used"], fits,
          "A slope of 1 means time doubles when the bit length doubles; a slope of 3 means it grows 8 times. " + note)

    checked, wrong = defaultdict(int), defaultdict(int)
    for r in rows:
        checked[r["algorithm"]] += int(r["instances"])
        wrong[r["algorithm"]] += int(r["wrong"])
    table("Wrong results found while timing", ["algorithm", "results checked", "wrong"],
          [[LABEL[a], checked[a], wrong[a]] for a in ALGOS if a in checked])


def time_vs_k():
    rows = read("time_k.csv")
    if not rows:
        return
    data = defaultdict(dict)
    for r in rows:
        data[r["algorithm"], r["family"]][int(r["k"])] = float(r["median_ns"]) / 1e3
    style = {"prime": "-", "rand_composite": ":", "carmichael": "--"}
    fig, ax = plt.subplots(figsize=(7.5, 4.2))
    for (a, fam), d in data.items():
        ax.plot(sorted(d), [d[k] for k in sorted(d)], style[fam], marker="o", ms=3, color=COLOR[a],
                label=f"{LABEL[a]}, {fam.replace('_', ' ')}")
    ax.set(xlabel="rounds k", ylabel="time per call (µs)", title="Time per call as rounds increase (60–64 bit inputs)")
    ax.legend(fontsize=8)
    save(fig, "time_vs_k.png")
    table("Time per call as rounds increase (60–64 bit inputs)", ["algorithm", "family", "k = 1", "k = 9", "k = 20", "k = 20 time ÷ k = 1 time"],
          [[LABEL[a], fam, fmt_ns(d[1] * 1e3), fmt_ns(d[9] * 1e3), fmt_ns(d[20] * 1e3), f"{d[20] / d[1]:.1f}"]
           for (a, fam), d in data.items()])


def error_vs_k():
    rows = read("error_vs_k.csv")
    if not rows:
        return
    subsets = list(dict.fromkeys(r["subset"] for r in rows))
    color = {s: plt.get_cmap("tab10")(i) for i, s in enumerate(subsets)}
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.2), sharey=True)
    for ax, a in zip(axes, ["fermat", "miller-rabin"]):
        for s in subsets:
            pts = [(int(r["k"]), float(r["rate"])) for r in rows
                   if r["algorithm"] == a and r["subset"] == s and float(r["rate"]) > 0]
            if pts:
                ax.plot(*zip(*pts), "o-", ms=3, color=color[s], label=s)
        ks = range(1, 21)
        ax.plot(ks, [4.0 ** -k for k in ks], "k--", lw=1, label="Miller-Rabin bound 4^-k")
        ax.set(yscale="log", xlabel="rounds k", title=LABEL[a], xticks=[1, 5, 10, 15, 20])
        ax.legend(fontsize=7)
    axes[0].set_ylabel("fraction of composites with a prime result")
    fig.suptitle("Error rate as rounds increase")
    save(fig, "error_vs_k.png")
    rate = {(r["algorithm"], r["subset"], int(r["k"])): r for r in rows}
    calls = rows[0]["calls"]
    table("Error rate as rounds increase", ["input family", "algorithm", "k = 1", "k = 3", "k = 9", "4^-9 bound"],
          [[s, LABEL[a]] + [f"{float(rate[a, s, k]['rate']):.2e} ({rate[a, s, k]['errors']})" for k in (1, 3, 9)]
           + ["3.81e-06"] for s in subsets for a in ["fermat", "miller-rabin"]],
          f"Each cell is the fraction of {int(calls):,} calls that returned prime, with the number of wrong results in brackets. 0 means there were none.")


def liars():
    rows = read("liars.csv")
    if not rows:
        return
    n = [int(r["n"]) for r in rows]
    fe = [float(r["fermat_liar_fraction"]) for r in rows]
    mr = [float(r["mr_liar_fraction"]) for r in rows]
    carm = [r["carmichael"] == "1" for r in rows]
    fig, ax = plt.subplots(figsize=(9, 4.8))
    ax.scatter(n, fe, s=2, color=COLOR["fermat"], alpha=0.5, label="Fermat")
    ax.scatter(n, mr, s=2, color=COLOR["miller-rabin"], alpha=0.5, label="Miller-Rabin")
    ax.scatter([x for x, c in zip(n, carm) if c], [y for y, c in zip(fe, carm) if c], s=40,
               facecolors="none", edgecolors="k", label="Carmichael number (Fermat)")
    ax.axhline(0.25, color="k", ls="--", lw=1, label="1/4, Miller-Rabin's proven limit")
    ax.set(xlabel="odd composite n", ylabel="fraction of bases with a prime result",
           title="Bases for which one round returns prime, odd composites up to 20,000")
    ax.legend(fontsize=8, markerscale=2, loc="upper center", bbox_to_anchor=(0.5, -0.15), ncol=4)
    save(fig, "liars.png")

    def worst(vals, keep):
        v, x = max((v, x) for v, x, k in zip(vals, n, keep) if k)
        return f"{v:.4f} (n = {x})"
    table("Bases for which one round returns prime (every base checked, odd composites up to 20,000)", ["measure", "value"], [
        ["odd composites checked", len(n)],
        ["Carmichael numbers among them", sum(carm)],
        ["highest fraction for Miller-Rabin", worst(mr, [True] * len(n))],
        ["highest fraction for Fermat, excluding Carmichael numbers", worst(fe, [not c for c in carm])],
        ["highest fraction for Fermat, Carmichael numbers", worst(fe, carm)],
        ["composites where Miller-Rabin's fraction is above 1/4", sum(v > 0.25 for v in mr)],
    ])


def carmichael():
    rows = read("carmichael_k1.csv")
    if not rows:
        return
    exact = {int(r["n"]): float(r["fermat_liar_fraction"]) for r in read("carmichael_fermat.csv", "data")}
    bits = [int(r["bits"]) for r in rows]
    fe = [float(r["fermat_k1_error"]) for r in rows]
    mr = [float(r["mr_k1_error"]) for r in rows]
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.scatter(bits, fe, s=6, color=COLOR["fermat"], alpha=0.6, label="Fermat")
    ax.scatter(bits, mr, s=6, color=COLOR["miller-rabin"], alpha=0.6, label="Miller-Rabin")
    ax.axhline(0.25, color="k", ls="--", lw=1, label="1/4")
    ax.set(xlabel="bits of n", ylabel="probability one round returns prime",
           title=f"One-round error on each of the {len(rows)} Carmichael numbers")
    ax.legend(fontsize=8, markerscale=2)
    save(fig, "carmichael_k1.png")
    gap = [abs(float(r["fermat_k1_error"]) - exact[int(r["n"])]) for r in rows if int(r["n"]) in exact]
    table("One-round error on Carmichael numbers", ["algorithm", "mean", "worst"],
          [[LABEL["fermat"], f"{sum(fe) / len(fe):.4f}", f"{max(fe):.4f}"],
           [LABEL["miller-rabin"], f"{sum(mr) / len(mr):.4f}", f"{max(mr):.4f}"]],
          f"Fermat's measured error is on average {sum(gap) / len(gap):.4f} away from the exact value (φ(n) − 2) / (n − 3)"
          f" ({rows[0]['trials']} trials per number), consistent with a correct Fermat implementation." if gap else "")


def tails():
    rows = read("tails.csv")
    if not rows:
        return
    subsets = list(dict.fromkeys(r["subset"] for r in rows))
    fig, ax = plt.subplots(figsize=(8, 4.2))
    w = 0.38
    for i, a in enumerate(["fermat", "miller-rabin"]):
        r = {x["subset"]: x for x in rows if x["algorithm"] == a}
        ax.bar([j + (i - 0.5) * w for j in range(len(subsets))],
               [float(r[s]["p99_ns"]) / float(r[s]["p50_ns"]) for s in subsets], w, color=COLOR[a], label=LABEL[a])
    ax.set_xticks(range(len(subsets)), [s.replace("_", "\n") for s in subsets], fontsize=8)
    ax.set(ylabel="99th percentile ÷ median call time", title="How much slower the slowest 1% of calls are (k = 9)")
    ax.legend()
    save(fig, "tails.png")
    table("Time per individual call (k = 9)", ["algorithm", "input family", "mean rounds", "wrong", "median", "p99", "p99.9", "p99 ÷ median"],
          [[LABEL[r["algorithm"]], r["subset"], f"{float(r['mean_rounds']):.3f}", f"{r['wrong']} / {r['calls']}",
            fmt_ns(float(r["p50_ns"])), fmt_ns(float(r["p99_ns"])), fmt_ns(float(r["p999_ns"])),
            f"{float(r['p99_ns']) / float(r['p50_ns']):.2f}"] for r in rows],
          f"Each call is timed on its own, so the times include reading the clock (resolution {rows[0]['timer_tick_ns']} ns).")


def aks_steps():
    rows = read("aks_steps.csv")
    if not rows:
        return
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(12, 4.2))
    for fam, m in (("prime", "o"), ("semiprime", "s")):
        rs = [r for r in rows if r["family"] == fam]
        a1.plot([int(r["bits"]) for r in rs], [int(r["r"]) for r in rs], m, color=COLOR["aks"], label=f"r ({fam})")
    a1.plot([int(r["bits"]) for r in rows], [float(r["log2n_sq"]) for r in rows], "k--", lw=1, label="log2(n)^2")
    a1.set(xlabel="bits of n", ylabel="r", title="Step 2: r found, compared with log2(n)^2")
    a1.legend(fontsize=8)
    primes = [r for r in rows if r["family"] == "prime"]
    for step, name in (("t_step1_s", "1 perfect power"), ("t_step2_s", "2 find r"), ("t_step3_s", "3 gcd"),
                       ("t_step5_s", "5 polynomial checks")):
        a2.plot([int(r["bits"]) for r in primes], [max(float(r[step]), 1e-9) for r in primes], "o-", ms=4, label=name)
    a2.set(yscale="log", xlabel="bits of n (primes)", ylabel="seconds", title="AKS time per step on primes")
    a2.legend(fontsize=8)
    save(fig, "aks_steps.png")
    table("AKS: one call per bit length, split by step", ["family", "bits", "deciding step", "r", "log2(n)^2", "values of a checked / required", "time in step 5", "total"],
          [[r["family"], r["bits"], r["verdict"], r["r"], r["log2n_sq"], f"{r['a_checked']} / {r['a_limit']}",
            f"{float(r['t_step5_s']) / float(r['total_s']):.1%}", fmt_ns(float(r["total_s"]) * 1e9)] for r in rows])


def aks_32bit():
    rows = read("aks_32bit.csv")
    if not rows:
        return
    by = defaultdict(list)
    for r in rows:
        by[int(r["bits"])].append(r)
    bits = sorted(by)
    med = lambda b, col: sorted(float(r[col]) for r in by[b])[len(by[b]) // 2]
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(12, 4.2))
    a1.plot([int(r["bits"]) for r in rows], [float(r["median_s"]) * 1e3 for r in rows], "o", ms=4, color=COLOR["aks"], alpha=0.5)
    a1.plot(bits, [med(b, "median_s") * 1e3 for b in bits], "-", color=COLOR["aks"])
    a1.set(yscale="log", xlabel="bits of n", ylabel="time per call (ms, log scale)", title="AKS on balanced semiprimes")
    a2.bar(bits, [med(b, "ns_per_coefficient_op") for b in bits], color=COLOR["aks"])
    a2.set(xlabel="bits of n", ylabel="ns", title="Time per coefficient multiply-add")
    for ax in (a1, a2):
        ax.axvline(32.5, color="k", ls="--", lw=1)
        ax.set_xticks(bits)
    save(fig, "aks_32bit.png")
    note = ""
    if 32 in by and 33 in by:
        note = f"From 32 to 33 bits the median time grows {med(33, 'median_s') / med(32, 'median_s'):.1f}×, while r grows only from {med(32, 'r'):.0f} to {med(33, 'r'):.0f}."
    table("AKS either side of 2^32 (balanced semiprimes, one value of a checked)",
          ["bits", "median r", "median time", "time per coefficient multiply-add", "correct"],
          [[b, f"{med(b, 'r'):.0f}", fmt_ns(med(b, "median_s") * 1e9), f"{med(b, 'ns_per_coefficient_op'):.2f} ns",
            f"{sum(r['correct'] == '1' for r in by[b])} / {len(by[b])}"] for b in bits], note)


if __name__ == "__main__":
    for chart in (time_vs_bits, time_vs_k, error_vs_k, tails, liars, carmichael, aks_steps, aks_32bit):
        chart()
    if os.path.exists(os.path.join(RES, "env.txt")):
        md.extend(["", "## Environment", "", "```", open(os.path.join(RES, "env.txt")).read().strip(), "```"])
    with open(os.path.join(RES, "summary.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    print("wrote summary.md")
